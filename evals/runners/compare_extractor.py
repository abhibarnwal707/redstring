"""Build evals/results/extractor_comparison.md from the saved extractor runs.

`python evals/runners/compare_extractor.py --worst qwen3-1.7b-qlora --worst-split test_annoctr`
Systems are rows, splits are blocks. The worst-errors section lists the examples where a chosen system disagrees
most with the gold labels (count of wrong + missed entities, techniques and relations)."""

import argparse
import json
from pathlib import Path

from redstring_cti.extractor import metrics

ROOT = Path(__file__).resolve().parents[2]
RUNS = ROOT / "evals" / "results" / "extractor"
DATA = ROOT / "finetune" / "data"
LABELS = {
    "base-zeroshot": "Qwen3-1.7B base, zero-shot",
    "base-3shot": "Qwen3-1.7B base, 3-shot",
    "qwen3-1.7b-qlora": "Qwen3-1.7B QLoRA v1 (2 epochs, cap 10)",
    "qwen3-1.7b-qlora-constrained": "QLoRA v1 + schema-constrained decoding",
    "qwen3-1.7b-qlora-rep11": "QLoRA v1 + repetition penalty 1.1",
    "qwen3-1.7b-qlora-v2-constrained": "QLoRA v2 + schema-constrained decoding",
    "qwen3-1.7b-qlora-v2": "Qwen3-1.7B QLoRA v2 (4 epochs, cap 25, real reports x3)",
    "api-gptoss120b": "API reference: gpt-oss-120b (Groq), zero-shot",
}
SPLITS = [("val", "Validation (197 rows: 150 ATT&CK sentences + 47 report chunks)"), ("test_annoctr", "Test: real-report chunks (AnnoCTR, 78)"), ("test_procedures", "Test: ATT&CK sentences (fixed sample of 100)")]


def fmt(r: dict) -> str:  # type: ignore[type-arg]
    return (f"{r['json_valid']:.1%} | {r['entity_exact']['f1']:.3f} | {r['technique_micro']['f1']:.3f} | {r['technique_macro_f1']:.3f} | "
            f"{r['relation']['f1']:.3f} | {r['id_hallucination']:.1%}")


def table() -> list[str]:
    lines: list[str] = []
    for split, title in SPLITS:
        found = [(name, json.loads((RUNS / f"{name}-{split}.metrics.json").read_text())) for name in LABELS if (RUNS / f"{name}-{split}.metrics.json").exists()]
        if not found:
            continue
        lines += [f"### {title}", "", "| System | Valid JSON | Entity F1 | Technique F1 (micro) | Technique F1 (macro) | Relation F1 | Made-up ids |", "|---|---|---|---|---|---|---|"]
        for name, m in found:
            lines.append(f"| {LABELS[name]} | {fmt(m['overall'])} |")
        extra = [(n, m["api_usage"]) for n, m in found if "api_usage" in m]
        for n, u in extra:
            lines.append(f"\nAPI cost for this split: ${u['total_cost_usd']} total, about ${u['cost_per_1k_docs_usd']} per 1,000 documents, median latency {u['median_latency_s']} s.")
        lines.append("")
    return lines


def worst(name: str, split: str, k: int) -> list[str]:
    path = RUNS / f"{name}-{split}.jsonl"
    texts = {json.loads(line)["id"]: json.loads(line)["messages"][1]["content"] for line in (DATA / f"{split}.jsonl").read_text().splitlines()}
    scored = []
    for line in path.read_text().splitlines():
        rec = json.loads(line)
        gold = metrics.parse(rec["gold"])
        pred = metrics.parse(rec["output"])
        assert gold is not None
        if pred is None:
            errors = 99
        else:
            ge, pe = {(e.text, e.type) for e in gold.entities}, {(e.text, e.type) for e in pred.entities}
            gt, pt = {t.attack_id for t in gold.techniques}, {t.attack_id for t in pred.techniques}
            errors = len(ge ^ pe) + len(gt ^ pt)
        scored.append((errors, rec))
    out = [f"## The {k} worst examples: {LABELS.get(name, name)} on {split}", ""]
    for errors, rec in sorted(scored, key=lambda x: (-x[0], x[1]["id"]))[:k]:
        text = texts.get(rec["id"], "")
        out += [f"**{rec['id']}** ({'invalid JSON' if errors == 99 else f'{errors} wrong or missing items'})", "", f"> {text[:400].replace(chr(10), ' ')}{'...' if len(text) > 400 else ''}", "",
                f"- gold: `{rec['gold'][:300]}`", f"- predicted: `{rec['output'][:300]}`", ""]
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--worst", default="qwen3-1.7b-qlora")
    ap.add_argument("--worst-split", default="test_annoctr")
    ap.add_argument("--k", type=int, default=10)
    args = ap.parse_args()
    lines = ["# Extractor comparison", "", ("Generated by `evals/runners/compare_extractor.py`. Entity F1 is exact (text and type). Technique F1 is on ATT&CK ids; "
             "macro averages over ids, so rare techniques count as much as common ones. Invalid JSON scores as an empty prediction. "
             "Relations are scored only on ATT&CK-sentence rows (AnnoCTR has no relation labels). The API model's output is cut to its outermost `{...}`."), ""]
    lines += table() + worst(args.worst, args.worst_split, args.k)
    (ROOT / "evals" / "results" / "extractor_comparison.md").write_text("\n".join(lines))
    print("\n".join(lines[:60]))


if __name__ == "__main__":
    main()
